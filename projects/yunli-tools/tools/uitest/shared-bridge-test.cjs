const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const code=fs.readFileSync(path.resolve(__dirname,"../../panel/js/tool-bridge.js"),"utf8");
(async()=>{
  const sent=[];
  const env={window:{chrome:{webview:{postMessage:m=>sent.push(m)}}},Uint8Array,TextDecoder,atob};
  vm.runInNewContext(code,env);
  const tool=env.window.YunLiTool;
  const progress=[];
  const marking=tool.request("marks",{size:6});
  const fonts=tool.requestNative("match",{session:"restore"},p=>progress.push(p.done));
  assert.notEqual(sent[0].id,sent[1].id,"两个模块必须使用唯一请求编号");
  assert.equal(sent[0].method,"tool");
  assert.equal(sent[1].method,"match");
  const deliver=message=>env.window.__zixingDeliver(Buffer.from(JSON.stringify(message)).toString("base64"));
  deliver({id:sent[1].id,eventType:"progress",data:{done:1}});
  deliver({id:sent[0].id,ok:true,data:{done:true}});
  deliver({id:sent[1].id,ok:true,data:{rows:[]}});
  assert.deepEqual(JSON.parse(JSON.stringify(await marking)),{done:true});
  assert.deepEqual(JSON.parse(JSON.stringify(await fonts)),{rows:[]});
  assert.deepEqual(progress,[1]);
  const failed=tool.requestNative("host",{action:"capture"});
  deliver({id:sent[2].id,ok:false,error:"取图失败"});
  await assert.rejects(failed,/取图失败/);
  const offline={window:{},Uint8Array,TextDecoder,atob};
  vm.runInNewContext(code,offline);
  await assert.rejects(offline.window.YunLiTool.request("inspect"),/Illustrator/);
  console.log("共用消息桥并发、进度、错误和未连接检查通过");
})().catch(e=>{console.error(e);process.exitCode=1;});
